export type TranslationKey = keyof typeof translations.en;

export function t(key: TranslationKey, lang: Language, params?: Record<string, string | number>): string {
  const dict = translations[lang] as Record<string, string> | undefined;
  let text: string = (dict && dict[key]) || translations.en[key] || key;
  if (params) {
    Object.entries(params).forEach(([k, v]) => {
      text = text.replace(`{${k}}`, String(v));
    });
  }
  return text;
}

export default translations;
